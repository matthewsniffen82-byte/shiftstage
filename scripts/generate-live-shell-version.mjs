import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { extractLiveShellAppScript } from "../src/lib/dancr/live-shell-script.mjs";
import { compactLiveShellScript } from "./lib/compact-live-shell-script.mjs";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const liveShellPath = path.join(repositoryRoot, "outputs", "index.html");
const generatedPath = path.join(repositoryRoot, "src", "generated", "live-shell-version.ts");
const liveShell = await readFile(liveShellPath, "utf8");
const normalizedLiveShell = liveShell.replace(/\r\n?/g, "\n");
const sha256 = createHash("sha256").update(normalizedLiveShell).digest("hex");
const generatedSource = [
  "// Generated by scripts/generate-live-shell-version.mjs.",
  "// This value makes the production root route rebuild whenever the live HTML changes.",
  `export const LIVE_SHELL_SHA256 = "${sha256}";`,
  "",
].join("\n");

const currentSource = await readFile(generatedPath, "utf8").catch(() => "");
if (currentSource !== generatedSource) {
  await writeFile(generatedPath, generatedSource, "utf8");
}

// Build once, never minify on a visitor's request. Hash the delivered bytes so
// minifier changes also receive a fresh URL instead of reusing an immutable one.
const script = await compactLiveShellScript(extractLiveShellAppScript(normalizedLiveShell));
const scriptHash = createHash("sha256").update(script).digest("hex");
const scriptPath = path.join(repositoryRoot, "outputs", "live-shell-app.js");
const scriptVersionPath = path.join(repositoryRoot, "src", "generated", "live-shell-script-version.mjs");
const scriptVersion = [
  "// Generated by scripts/generate-live-shell-version.mjs.",
  `export const LIVE_SHELL_SCRIPT_SHA256 = "${scriptHash}";`,
  "",
].join("\n");
for (const [target, content] of [[scriptPath, script], [scriptVersionPath, scriptVersion]]) {
  if (await readFile(target, "utf8").catch(() => "") !== content) {
    await writeFile(target, content, "utf8");
  }
}
