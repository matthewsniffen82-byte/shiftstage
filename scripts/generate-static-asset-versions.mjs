import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { staticAssetPaths } from "../src/lib/dancr/static-asset-paths.mjs";

const versions = {};
for (const asset of staticAssetPaths) {
  const bytes = await readFile(new URL(`../public${asset}`, import.meta.url));
  const content = /\.(css|js|svg)$/.test(asset) ? bytes.toString("utf8").replace(/\r\n?/g, "\n") : bytes;
  versions[asset] = createHash("sha256").update(content).digest("hex").slice(0, 16);
}
const target = new URL("../src/generated/static-asset-versions.mjs", import.meta.url);
const source = `// Generated by scripts/generate-static-asset-versions.mjs. Do not edit.\nexport const staticAssetVersions = ${JSON.stringify(versions, null, 2)};\n`;
if (await readFile(target, "utf8").catch(() => "") !== source) await writeFile(target, source);
